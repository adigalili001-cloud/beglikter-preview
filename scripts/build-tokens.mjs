// Turns design/tokens.figma.json (exported from the Figma variables) into src/styles/tokens.css.
// Names come from each variable's WEB code syntax in Figma, so CSS and Figma always speak the same names.
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../design/tokens.figma.json', import.meta.url), 'utf8'));
const prop = (syntax) => syntax.replace(/^var\((--[^)]+)\)$/, '$1');

const groups = new Map();
for (const [collection, name, syntax, value] of src.variables) {
  let css;
  if (value && typeof value === 'object' && value.alias) css = value.alias;
  else if (typeof value === 'number') css = `${value}px`;
  else if (name.startsWith('font/')) css = `"${value}", system-ui, sans-serif`;
  else css = value;
  if (!groups.has(collection)) groups.set(collection, []);
  groups.get(collection).push(`  ${prop(syntax)}: ${css}; /* ${name} */`);
}

let out = '/* GENERATED by scripts/build-tokens.mjs from design/tokens.figma.json — do not edit by hand. */\n:root {\n';
for (const [collection, lines] of groups) out += `\n  /* ${collection} */\n${lines.join('\n')}\n`;
out += '}\n';
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), out);
console.log(`tokens.css: ${src.variables.length} variables`);
