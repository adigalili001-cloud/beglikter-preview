// Turns design/tokens.figma.json (exported from the Figma variables) into src/styles/tokens.css.
// Names come from each variable's WEB code syntax in Figma, so CSS and Figma always speak the same names.
//
// Each entry: [collection, name, webSyntax, defaultValue, { ModeName: value }?]
// The first mode (Desktop) is the default in :root. Other modes only list values that differ,
// and become media-query overrides — same names as the Figma artboard breakpoints.
import { readFileSync, writeFileSync } from 'node:fs';

const MODE_MEDIA = {
  Tablet: '(max-width: 1023px)',
  Mobile: '(max-width: 599px)', // after Tablet, so it wins on phones
};

// Fallbacks after each font token. Almoni is licensed and its web files aren't in the repo yet —
// until they are, Latin shows in Schibsted Grotesk and Hebrew in Noto Sans Hebrew (both bundled via @fontsource).
const FONT_FALLBACK = '"Schibsted Grotesk", "Noto Sans Hebrew", system-ui, sans-serif';

const src = JSON.parse(readFileSync(new URL('../design/tokens.figma.json', import.meta.url), 'utf8'));
const prop = (syntax) => syntax.replace(/^var\((--[^)]+)\)$/, '$1');
const toCss = (name, value) => {
  if (value && typeof value === 'object' && value.alias) return value.alias;
  if (typeof value === 'number') return `${+value.toFixed(3)}px`;
  if (name.startsWith('font/')) return `"${value}", ${FONT_FALLBACK}`;
  return value;
};

const groups = new Map();
const overrides = Object.fromEntries(Object.keys(MODE_MEDIA).map((m) => [m, []]));
for (const [collection, name, syntax, value, modes = {}] of src.variables) {
  if (!groups.has(collection)) groups.set(collection, []);
  groups.get(collection).push(`  ${prop(syntax)}: ${toCss(name, value)}; /* ${name} */`);
  for (const [mode, v] of Object.entries(modes)) {
    if (!MODE_MEDIA[mode]) throw new Error(`Unknown mode "${mode}" on ${name} — add it to MODE_MEDIA`);
    overrides[mode].push(`    ${prop(syntax)}: ${toCss(name, v)}; /* ${name} */`);
  }
}

let out = '/* GENERATED by scripts/build-tokens.mjs from design/tokens.figma.json — do not edit by hand. */\n:root {\n';
for (const [collection, lines] of groups) out += `\n  /* ${collection} */\n${lines.join('\n')}\n`;
out += '}\n';
for (const [mode, lines] of Object.entries(overrides)) {
  if (lines.length) out += `\n/* Mode: ${mode} */\n@media ${MODE_MEDIA[mode]} {\n  :root {\n${lines.join('\n')}\n  }\n}\n`;
}
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), out);
const n = Object.values(overrides).reduce((a, l) => a + l.length, 0);
console.log(`tokens.css: ${src.variables.length} variables, ${n} mode overrides`);
